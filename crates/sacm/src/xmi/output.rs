//! The XMI writer (SACM23-XMI-003, -004, -005, -006, -007, -011, -012, -013,
//! -017, SACM23-BASE-004, -005, -006, -007, -008, LIB-API-010,
//! LIB-COMPAT-007, SACM23-ARG-004, -005, -007; ADR 0017, ADR 0022, ADR 0025,
//! ADR 0026, ADR 0027).
//!
//! Two passes. [`plan`] checks the document (in strict mode, refusing
//! preserved content and output that would not be schema-valid, ADR 0035
//! D4) and every element, and resolves what each is written as; only if that
//! succeeds does [`write`] build the `String` from the plan,
//! so a refusal never leaves partial output, and the output pass has no
//! lookup that could fail. The output form is pinned byte for byte: UTF-8
//! without a BOM, the XML declaration, LF line endings, two spaces per depth,
//! one tag per line and `<x … />` for an element with no children.
//! Preserved content (LIB-COMPAT-003, ADR 0033) is written back where it
//! was read: its attributes after the typed ones, each child on its own line
//! before the typed child it preceded, a fragment as one line with its text
//! exactly as held, each declaring the namespace bindings it needs. The
//! document's own preserved content, outside every element, is written on
//! and in the `xmi:XMI` element, its children among the roots; a document
//! that holds some is always wrapped (ADR 0035 D3). XMI metadata
//! (SACM23-XMI-019, ADR 0042) is written back the same way in both modes:
//! its attributes before the preserved ones, its children before the
//! preserved children placed at the same index, a part's after its typed
//! attributes and among its values; a document that holds some outside
//! every element is wrapped too. Neither pass recurses, so deep nesting is
//! safe.

use super::namespaces::{SACM_NS, SACM_PREFIX, XMI_NS, XMI_PREFIX};
use super::{Mode, WriteAttribute, WriteError};
use crate::model::{
    AbstractClass, AssertionDeclaration, Attr, DeclaredType, Document, ElementId, ElementKind,
    Event, Flag, Fragment, Href, Item, LangString, OWNERS, Preserved, QName, ReferenceEnd,
    SacmElement, StringAttribute, Text, TextRole,
};
use crate::validation;

/// Line 1 of every output.
const DECLARATION: &str = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>";

/// `document` written as XMI in `mode`, or the first reason it cannot be.
///
/// The bound in the `write` docs, "# Output size", for a document read from
/// B bytes under a depth limit D and a size limit M, (2·D + 48)·B + 6·M +
/// 8,192, adds up these, each a bound on what the output can hold:
/// - lines: at most B/2 + 3, since every written line comes from an element,
///   an attribute or a text of at least two input bytes, plus the
///   declaration, a wrapper's start tag and its end tag;
/// - indentation: at most 2(D + 2) bytes per line, two per level, the
///   wrapper and a value element's level included;
/// - escaping: at most six output bytes per input byte (`"` is `&quot;`);
/// - generated bytes: at most 98 per element of at least four input bytes
///   (its `xmi:type`, a generated `xmi:id`, and the start and end tags a
///   C++ shape expands to);
/// - written declarations: at most six bytes per byte of namespace text kept
///   by preserved content, which the size limit bounds by M (ADR 0041 D2);
/// - 8,192 bytes of fixed text: the declaration and the document element's
///   namespace declarations.
pub(super) fn write(document: &Document, mode: Mode) -> Result<String, WriteError> {
    let plan = plan(document, mode)?;
    // The XMI metadata and the preserved content outside every element, with
    // how many of their children are written so far, and how many roots
    // (ADR 0035 D3, ADR 0042).
    let mut outside = Placing::new(document.document_metadata(), document.document_preserved());
    let mut roots_written = 0_usize;
    let wrapped = document.roots().nth(1).is_some() || outside.holds_any();
    let mut out = String::new();
    out.push_str(DECLARATION);
    out.push('\n');
    let base = if wrapped {
        push_wrapper_start(&mut out, &outside);
        1
    } else {
        0
    };

    // The elements whose start tag is written and whose end tag is not, the
    // innermost last. The plan is in pre-order, so an element's parent is
    // on this stack when the element comes.
    let mut open: Vec<Open<'_, '_>> = Vec::new();
    for planned in &plan {
        let parent = planned.element.parent().map(SacmElement::id);
        while let Some(top) = open.last() {
            if Some(top.planned.element.id()) == parent {
                break;
            }
            if let Some(top) = open.pop() {
                close(&mut out, base + open.len(), top);
            }
        }
        let depth = base + open.len();
        // The parent's metadata and preserved children placed before this one
        // (ADR 0033, ADR 0042), or, before a root, the document's (ADR 0035
        // D3).
        if let Some(top) = open.last_mut() {
            top.placing.push(&mut out, depth, Some(top.written));
            top.written = top.written.saturating_add(1);
        } else {
            outside.push(&mut out, depth, Some(roots_written));
            roots_written = roots_written.saturating_add(1);
        }
        let placing = Placing::new(planned.element.metadata(), planned.element.preserved());
        let as_elements = push_start_tag(&mut out, depth, planned);
        let name = planned.element.name();
        let texts = TextRole::ALL.map(|role| (role, planned.element.text(role)));
        let has_texts = texts.iter().any(|(_, text)| text.is_some());
        let has_placed = placing.places_any();
        if name.is_some()
            || has_texts
            || has_placed
            || !as_elements.is_empty()
            || planned.element.children().next().is_some()
            || !planned.element.proxies().is_empty()
        {
            out.push_str(">\n");
            if let Some(name) = name {
                let part = Part {
                    id: planned.element.name_id(),
                    metadata: planned.element.name_metadata(),
                };
                push_lang_string(&mut out, depth + 1, "name", name, part);
            }
            // `content` before `key`, superclass first (XMI 2.5.1 Annex
            // B.5.2), and a Resource's `location` after its name (ADR 0034
            // amendment 1).
            for (role, text) in texts {
                if let Some(text) = text {
                    push_text(&mut out, depth + 1, role, text);
                }
            }
            push_reference_elements(&mut out, depth + 1, planned.element, &as_elements);
            open.push(Open {
                planned,
                written: 0,
                placing,
            });
        } else {
            out.push_str(" />\n");
        }
    }
    while let Some(top) = open.pop() {
        close(&mut out, base + open.len(), top);
    }
    outside.push(&mut out, base, None);

    if wrapped {
        out.push_str("</");
        push_wrapper_name(&mut out);
        out.push_str(">\n");
    }
    Ok(out)
}

/// Writes the start tag of `planned` at `depth`, up to its `>`: its name,
/// the document element's namespace declarations at depth 0, its type, id
/// and gid, its flags, declaration and references, its string-valued
/// attributes, and its preserved attributes. Returns the ends written in the element form instead
/// ([`ends_as_elements`]).
fn push_start_tag(out: &mut String, depth: usize, planned: &Planned<'_>) -> Vec<ReferenceEnd> {
    indent(out, depth);
    out.push('<');
    push_tag(out, &planned.tag);
    if depth == 0 {
        push_document_attributes(out);
    }
    if let Some(kind) = planned.written_type {
        push_attribute_name(out, "type");
        out.push_str(SACM_PREFIX);
        out.push(':');
        out.push_str(kind.name());
        out.push('"');
    }
    push_attribute_name(out, "id");
    escape_into(out, planned.element.id().as_str());
    out.push('"');
    // A gid comes directly after the id (ADR 0025), escaped like it.
    if let Some(gid) = planned.element.gid() {
        out.push_str(" gid=\"");
        escape_into(out, gid);
        out.push('"');
    }
    // Then the flags, the declaration and the references, class by class,
    // superclass first (Annex B.5.2; ADR 0027). An end the element also
    // holds as a preserved attribute of the same name (which held no id) is
    // written in the element form, so that no start tag carries one
    // attribute twice (ADR 0033).
    let as_elements = ends_as_elements(planned.element);
    push_flags_and_references(out, planned.element, planned.declaration, &as_elements);
    // Then the kind's string-valued attributes, `version`, `date`,
    // `startTime`, `endTime`, `value` and `externalReference`, each exactly
    // as held and escaped (ADR 0034 amendments 1 and 3, D-DATE).
    for attribute in StringAttribute::ALL {
        if let Some(value) = planned.element.string(attribute) {
            out.push(' ');
            out.push_str(attribute.name());
            out.push_str("=\"");
            escape_into(out, value);
            out.push('"');
        }
    }
    // Then the bindings of the metadata and the preserved attributes, then
    // the metadata attributes and the preserved ones, each in input order
    // (ADR 0033, ADR 0042).
    push_kept_attributes(out, planned.element.metadata(), planned.element.preserved());
    as_elements
}

/// The ends of `element` written in the element form, in
/// [`ReferenceEnd::ALL`] order: each that holds a cross-document reference,
/// which only an element can carry (ADR 0040 D4), and each that holds an id
/// and that the element also holds, as preserved content, as an attribute of
/// the same name, which held no id, so that no start tag carries one
/// attribute twice (ADR 0033).
fn ends_as_elements(element: SacmElement<'_>) -> Vec<ReferenceEnd> {
    let preserved = element.preserved();
    ReferenceEnd::ALL
        .iter()
        .copied()
        .filter(|end| {
            !end.is_derived()
                && (!element.hrefs(*end).is_empty()
                    || (!element.references(*end).is_empty()
                        && preserved.is_some_and(|held| held.has_unqualified(end.name()))))
        })
        .collect()
}

/// Writes the attributes of `metadata` and `preserved`, if any, each after a
/// space: the namespace bindings they need, once per prefix and sorted by
/// it, then the metadata attributes, then the preserved ones, each in input
/// order (ADR 0033, ADR 0042).
fn push_kept_attributes(
    out: &mut String,
    metadata: Option<&Preserved>,
    preserved: Option<&Preserved>,
) {
    let mut bindings: Vec<&(String, String)> = metadata
        .into_iter()
        .chain(preserved)
        .flat_map(|kept| &kept.namespaces)
        .collect();
    bindings.sort();
    bindings.dedup_by(|later, earlier| later.0 == earlier.0);
    for (prefix, uri) in bindings {
        push_namespace(out, Some(prefix), uri);
    }
    for attr in metadata
        .into_iter()
        .chain(preserved)
        .flat_map(|kept| &kept.attributes)
    {
        push_attr(out, attr);
    }
}

/// Writes each id that an end of `ends` of `element` holds as a reference
/// element `<end xmi:idref="…" />`, then each cross-document reference as
/// `<end href="…" />`, each on its own line at `depth` (XMI 2.5.1 rule 2l;
/// ADR 0040 D4), in order.
fn push_reference_elements(
    out: &mut String,
    depth: usize,
    element: SacmElement<'_>,
    ends: &[ReferenceEnd],
) {
    for &end in ends {
        // The ids first, then the `href`s: how a file interleaved them is
        // not kept (ADR 0040 D3, D-ORDER).
        for target in element.references(end) {
            indent(out, depth);
            out.push('<');
            out.push_str(end.name());
            push_attribute_name(out, "idref");
            escape_into(out, target.as_str());
            out.push_str("\" />\n");
        }
        for href in element.hrefs(end) {
            push_href_element(out, depth, end.name(), href);
        }
    }
}

/// An element whose start tag is written and whose end tag is not.
struct Open<'p, 'a> {
    /// The element.
    planned: &'p Planned<'a>,
    /// The number of its typed children written so far.
    written: usize,
    /// Its metadata and preserved children, and how many of each are
    /// written so far.
    placing: Placing<'a>,
}

/// What a holder places among its typed children, an element's or the
/// document's: its XMI metadata (ADR 0042) and its preserved content (ADR
/// 0033), with how many children of each are written so far.
struct Placing<'a> {
    metadata: Option<&'a Preserved>,
    preserved: Option<&'a Preserved>,
    /// The number of metadata children written.
    metadata_placed: usize,
    /// The number of preserved children written.
    preserved_placed: usize,
}

impl<'a> Placing<'a> {
    /// Nothing written yet of `metadata` and `preserved`.
    fn new(metadata: Option<&'a Preserved>, preserved: Option<&'a Preserved>) -> Self {
        Self {
            metadata,
            preserved,
            metadata_placed: 0,
            preserved_placed: 0,
        }
    }

    /// Whether it holds anything, attributes included.
    fn holds_any(&self) -> bool {
        self.metadata.is_some() || self.preserved.is_some()
    }

    /// Whether it places a child.
    fn places_any(&self) -> bool {
        self.metadata
            .into_iter()
            .chain(self.preserved)
            .any(|kept| !kept.children.is_empty())
    }

    /// Writes, at `depth`, the children not written yet that are placed
    /// before the typed child at index `before`, or all of them for `None`:
    /// the metadata children first, then the preserved ones (ADR 0042).
    fn push(&mut self, out: &mut String, depth: usize, before: Option<usize>) {
        if let Some(metadata) = self.metadata {
            push_placed(out, depth, metadata, &mut self.metadata_placed, before);
        }
        if let Some(preserved) = self.preserved {
            push_placed(out, depth, preserved, &mut self.preserved_placed, before);
        }
    }
}

/// Writes, at `depth`, the children of `preserved` after the first
/// `written` that are placed before the typed child at index `before`, or
/// all of them for `None`, each on its own line, and counts them in
/// `written` (ADR 0033).
fn push_placed(
    out: &mut String,
    depth: usize,
    preserved: &Preserved,
    written: &mut usize,
    before: Option<usize>,
) {
    for placed in preserved.children.iter().skip(*written) {
        if before.is_some_and(|before| placed.index > before) {
            break;
        }
        indent(out, depth);
        match &placed.item {
            Item::Text(text) => escape_text_into(out, text),
            Item::Element(fragment) => push_fragment(out, fragment),
        }
        out.push('\n');
        *written = written.saturating_add(1);
    }
}

/// Writes the rest of the element `top`, whose start tag is at `depth`: its
/// preserved children not written yet, then its end tag.
/// Its proxies come last, one line each, `<role href="…" />`, in held order
/// (ADR 0040 amendment 1, A3).
fn close(out: &mut String, depth: usize, mut top: Open<'_, '_>) {
    top.placing.push(out, depth + 1, None);
    for proxy in top.planned.element.proxies() {
        push_href_element(out, depth + 1, proxy.role(), proxy.href());
    }
    push_end_tag(out, depth, &top.planned.tag);
}

/// Writes `<tag href="…" />` on its own line at `depth`: a cross-document
/// reference, a proxy, or the `expression` of an `ExpressionLangString`, the
/// value escaped (XMI 2.5.1 rule 2m; ADR 0040 D4).
fn push_href_element(out: &mut String, depth: usize, tag: &str, href: &Href) {
    indent(out, depth);
    out.push('<');
    out.push_str(tag);
    out.push_str(" href=\"");
    escape_into(out, href.as_str());
    out.push_str("\" />\n");
}

/// Writes `fragment`, preserved content (ADR 0033), on the current line:
/// each element with its bindings, then its attributes, and `<x … />` when
/// it holds nothing; its text exactly, escaped. Flat, so never recursive.
fn push_fragment(out: &mut String, fragment: &Fragment) {
    let mut names: Vec<&QName> = Vec::new();
    let mut events = fragment.events.iter().peekable();
    while let Some(event) = events.next() {
        match event {
            Event::Start {
                name,
                namespaces,
                attributes,
            } => {
                out.push('<');
                push_qname(out, name);
                for (prefix, uri) in namespaces {
                    push_namespace(out, prefix.as_deref(), uri);
                }
                for attr in attributes {
                    push_attr(out, attr);
                }
                if matches!(events.peek(), Some(Event::End)) {
                    events.next();
                    out.push_str(" />");
                } else {
                    out.push('>');
                    names.push(name);
                }
            }
            Event::Text(text) => escape_text_into(out, text),
            Event::End => {
                if let Some(name) = names.pop() {
                    out.push_str("</");
                    push_qname(out, name);
                    out.push('>');
                }
            }
        }
    }
}

/// Writes ` xmlns:<prefix>="<uri>"`, or ` xmlns="<uri>"` for the default
/// namespace, escaped.
fn push_namespace(out: &mut String, prefix: Option<&str>, uri: &str) {
    out.push_str(" xmlns");
    if let Some(prefix) = prefix {
        out.push(':');
        out.push_str(prefix);
    }
    out.push_str("=\"");
    escape_into(out, uri);
    out.push('"');
}

/// Writes ` <name>="<value>"`, escaped.
fn push_attr(out: &mut String, attr: &Attr) {
    out.push(' ');
    push_qname(out, &attr.name);
    out.push_str("=\"");
    escape_into(out, &attr.value);
    out.push('"');
}

/// Writes `name` as written: `prefix:local`, or `local`.
fn push_qname(out: &mut String, name: &QName) {
    if let Some(prefix) = &name.prefix {
        out.push_str(prefix);
        out.push(':');
    }
    out.push_str(&name.local);
}

/// Writes `text` as character data: `&`, `<`, `>` and CR escaped, so it
/// reads back as it is held; everything else, TAB and LF included, as it
/// is.
fn escape_text_into(out: &mut String, text: &str) {
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '\r' => out.push_str("&#13;"),
            other => out.push(other),
        }
    }
}

/// One element, checked, with what it is written as.
struct Planned<'a> {
    /// The element.
    element: SacmElement<'a>,
    /// Its element name.
    tag: Tag,
    /// The class written as its `xmi:type`, if one is.
    written_type: Option<ElementKind>,
    /// Its `assertionDeclaration`, if it is an Assertion not declared
    /// `asserted`, the default, which is not written (XMI 2.5.1 §9.4.1).
    declaration: Option<AssertionDeclaration>,
}

/// The element name an element is written under.
enum Tag {
    /// A root: `sacm:<Kind>`.
    Root(ElementKind),
    /// A child: the name of the role of its parent's class that holds it.
    Role(&'static str),
}

/// Checks `document` in ADR 0035 D4's order: a root first (ADR 0035
/// amendment 1);
/// then, in strict `mode`, preserved content and the schema check; then each
/// element in document order (see [`unrepresentable`]); and returns every
/// element in that order with what it is written as. Everything a document
/// holds is written, so these are the only refusals.
fn plan(document: &Document, mode: Mode) -> Result<Vec<Planned<'_>>, WriteError> {
    if document.roots().next().is_none() {
        // An `xmi:XMI` holding only XMI metadata holds no package, which a
        // reader refuses (`ReadError::NoPackage`), so it is not written.
        return Err(WriteError::NoRoot);
    }
    if mode == Mode::Strict {
        // The writer cannot show that content it did not read is
        // schema-valid: each holder once, in document order, before the
        // schema check (SACM23-XMI-008, ADR 0033, ADR 0035 D4). Content
        // outside every element names no holder.
        let elements: Vec<ElementId> = document
            .elements()
            .filter(|element| element.has_preserved_content())
            .map(|element| element.id().clone())
            .collect();
        if !elements.is_empty() || document.document_preserved().is_some() {
            return Err(WriteError::preserved_content(elements));
        }
        // Every schema error, in `Diagnostic` order; never `validate` (ADR
        // 0035 D4).
        let diagnostics = validation::schema_errors(document);
        if !diagnostics.is_empty() {
            return Err(WriteError::invalid(diagnostics));
        }
    }
    let mut plan = Vec::new();
    for element in document.elements() {
        if let Some((attribute, character)) = unrepresentable(element) {
            return Err(WriteError::unrepresentable_character(
                element.id().clone(),
                character,
                attribute,
            ));
        }
        let kind = element.kind();
        // A child keeps the role it was added in; a root has none.
        let (tag, written_type) = match element.role() {
            None => (Tag::Root(kind), None),
            Some(role) => {
                let written_type = match role.declared {
                    DeclaredType::Kind(declared) if declared == kind => None,
                    DeclaredType::Kind(_) | DeclaredType::Abstract(_) => Some(kind),
                };
                (Tag::Role(role.name), written_type)
            }
        };
        let declaration = element
            .assertion_declaration()
            .filter(|&declaration| declaration != AssertionDeclaration::default());
        plan.push(Planned {
            element,
            tag,
            written_type,
            declaration,
        });
    }
    Ok(plan)
}

/// The first value `element` holds that XML 1.0 cannot represent, as the
/// attribute that holds it and its first such character, checked in this
/// order: its id, its gid, its `version`, `date`, `startTime`, `endTime`,
/// `value` and `externalReference`, its name's `lang` and `content`, then each value of its
/// `content`, then of its `key` and then of its `location`, `lang` before
/// `content`. The ids of a name, `content`, `key`, `location` or `value`
/// are not checked: only
/// [`xmi::read`](crate::xmi::read) gives them, and what it reads is
/// representable. Nor are the ids a reference holds: they are element ids,
/// which `xmi::read` or a checked `with_id` gave, or ids `xmi::read` read
/// from a reference, and each of those is representable.
fn unrepresentable(element: SacmElement<'_>) -> Option<(WriteAttribute, char)> {
    let name = element.name();
    let fields = [
        (WriteAttribute::Id, Some(element.id().as_str())),
        (WriteAttribute::Gid, element.gid()),
        (WriteAttribute::Version, element.version()),
        (WriteAttribute::Date, element.date()),
        (WriteAttribute::StartTime, element.start_time()),
        (WriteAttribute::EndTime, element.end_time()),
        (WriteAttribute::Value, element.value()),
        (
            WriteAttribute::ExternalReference,
            element.external_reference(),
        ),
        (WriteAttribute::NameLang, name.and_then(LangString::lang)),
        (
            WriteAttribute::NameContent,
            name.and_then(LangString::content),
        ),
    ];
    let texts = [
        (
            TextRole::Content,
            WriteAttribute::ContentValueLang,
            WriteAttribute::ContentValueContent,
        ),
        (
            TextRole::Key,
            WriteAttribute::KeyValueLang,
            WriteAttribute::KeyValueContent,
        ),
        (
            TextRole::Location,
            WriteAttribute::LocationValueLang,
            WriteAttribute::LocationValueContent,
        ),
    ];
    let values = texts.into_iter().flat_map(move |(role, lang, content)| {
        element
            .text(role)
            .map_or(&[][..], |text| text.value().values())
            .iter()
            .flat_map(move |value| [(lang, value.lang()), (content, value.content())])
    });
    fields
        .into_iter()
        .chain(values)
        .find_map(|(attribute, value)| {
            value
                .and_then(|value| value.chars().find(|&c| !is_xml_char(c)))
                .map(|character| (attribute, character))
        })
}

/// Whether `c` is an XML 1.0 `Char` (§2.2). A Rust `char` is never a
/// surrogate.
fn is_xml_char(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n' | '\r' | ' '..='\u{D7FF}' | '\u{E000}'..='\u{FFFD}' | '\u{10000}'..='\u{10FFFF}'
    )
}

/// Writes the flags of `element`, its `declaration` and its references as
/// attributes, each after a space (ADR 0026, ADR 0027): for each class that
/// owns some of them and that the element's kind specializes, superclass
/// first ([`OWNERS`]), the class's flags, then, on `Assertion`, the
/// declaration, then the class's ends, each in table order. A flag is
/// written only when true, as `"true"`, the declaration only when given,
/// and an end only when it holds an id, as its ids in order, separated by
/// one space, each escaped (`xsd:IDREFS`, XMI 2.5.1 rule 2j). The ends of
/// `as_elements` are not: the caller writes them as reference elements.
fn push_flags_and_references(
    out: &mut String,
    element: SacmElement<'_>,
    declaration: Option<AssertionDeclaration>,
    as_elements: &[ReferenceEnd],
) {
    let kind = element.kind();
    for owner in OWNERS.into_iter().filter(|owner| owner.admits(kind)) {
        for flag in Flag::ALL
            .iter()
            .copied()
            .filter(|flag| flag.owner() == owner)
        {
            if element.flag(flag) {
                out.push(' ');
                out.push_str(flag.name());
                out.push_str("=\"true\"");
            }
        }
        if owner == DeclaredType::Abstract(AbstractClass::Assertion) {
            if let Some(declaration) = declaration {
                out.push_str(" assertionDeclaration=\"");
                out.push_str(declaration.as_str());
                out.push('"');
            }
        }
        // The derived `expression` is written with the name and the texts
        // that hold it (SACM23-BASE-009).
        for end in ReferenceEnd::ALL
            .iter()
            .copied()
            .filter(|end| end.owner_on(kind) == Some(owner) && !end.is_derived())
        {
            let targets = element.references(end);
            if targets.is_empty() || as_elements.contains(&end) {
                continue;
            }
            out.push(' ');
            out.push_str(end.name());
            out.push_str("=\"");
            for (position, target) in targets.iter().enumerate() {
                if position > 0 {
                    out.push(' ');
                }
                escape_into(out, target.as_str());
            }
            out.push('"');
        }
    }
}

/// The `xmi:id` and the XMI metadata of a part: a `name`, a `content`, `key`
/// or `location`, or a `value` in one (ADR 0024, ADR 0025, ADR 0042).
#[derive(Clone, Copy)]
struct Part<'a> {
    id: Option<&'a ElementId>,
    metadata: Option<&'a Preserved>,
}

/// Writes `value` as a `tag` element on its own line at `depth`: for an
/// `ExpressionLangString`, `xmi:type="sacm:ExpressionLangString"` first
/// (SACM23-BASE-009, ADR 0038 D2); then the part's `id`, as `xmi:id`, then
/// `lang`, then `content`, then an `ExpressionLangString`'s `expression`,
/// each only if present (ADR 0017, ADR 0024), then the part's XMI metadata
/// attributes, after the bindings they need (ADR 0042): a `name`, or a
/// `value` of a `content`, `key` or `location`. Metadata children make it a
/// start and an end tag, with each child on its own line between them.
fn push_lang_string(out: &mut String, depth: usize, tag: &str, value: &LangString, part: Part<'_>) {
    indent(out, depth);
    out.push('<');
    out.push_str(tag);
    if value.is_expression_lang_string() {
        out.push_str(" xmi:type=\"");
        out.push_str(SACM_PREFIX);
        out.push_str(":ExpressionLangString\"");
    }
    push_id(out, part.id);
    let expression = value.expression().map(ElementId::as_str);
    for (attribute, value) in [
        ("lang", value.lang()),
        ("content", value.content()),
        ("expression", expression),
    ] {
        if let Some(value) = value {
            out.push(' ');
            out.push_str(attribute);
            out.push_str("=\"");
            escape_into(out, value);
            out.push('"');
        }
    }
    push_kept_attributes(out, part.metadata, None);
    let mut placing = Placing::new(part.metadata, None);
    // An expression in another document is an `expression` reference
    // element, the first child (ADR 0040 amendment 1, A3).
    let href = value.expression_href();
    if href.is_none() && !placing.places_any() {
        out.push_str(" />\n");
        return;
    }
    out.push_str(">\n");
    if let Some(href) = href {
        push_href_element(out, depth + 1, "expression", href);
    }
    placing.push(out, depth + 1, None);
    push_end(out, depth, tag);
}

/// Writes `text` as its `role` element at `depth`, with its `xmi:id` first,
/// then its XMI metadata attributes (ADR 0042), and one `value` element per
/// value under it, in order, each metadata child of the role element before
/// the value it was read before; with no values and no metadata children,
/// one empty element (ADR 0025).
fn push_text(out: &mut String, depth: usize, role: TextRole, text: &Text) {
    indent(out, depth);
    out.push('<');
    out.push_str(role.name());
    push_id(out, text.id());
    push_kept_attributes(out, text.role_metadata(), None);
    let values = text.value().values();
    let mut placing = Placing::new(text.role_metadata(), None);
    if values.is_empty() && !placing.places_any() {
        out.push_str(" />\n");
        return;
    }
    out.push_str(">\n");
    let parts = text.value_ids().iter().zip(text.value_metadata());
    for (index, (value, (id, metadata))) in values.iter().zip(parts).enumerate() {
        placing.push(out, depth + 1, Some(index));
        let part = Part {
            id: id.as_ref(),
            metadata: metadata.as_deref(),
        };
        push_lang_string(out, depth + 1, "value", value, part);
    }
    placing.push(out, depth + 1, None);
    push_end(out, depth, role.name());
}

/// Writes the end tag `</tag>` on its own line at `depth`.
fn push_end(out: &mut String, depth: usize, tag: &str) {
    indent(out, depth);
    out.push_str("</");
    out.push_str(tag);
    out.push_str(">\n");
}

/// Writes ` xmi:id="<id>"`, escaped, if there is an id.
fn push_id(out: &mut String, id: Option<&ElementId>) {
    if let Some(id) = id {
        push_attribute_name(out, "id");
        escape_into(out, id.as_str());
        out.push('"');
    }
}

/// Writes the element name `tag`.
fn push_tag(out: &mut String, tag: &Tag) {
    match tag {
        Tag::Root(kind) => {
            out.push_str(SACM_PREFIX);
            out.push(':');
            out.push_str(kind.name());
        }
        Tag::Role(name) => out.push_str(name),
    }
}

/// Writes the end tag of `tag` on its own line at `depth`.
fn push_end_tag(out: &mut String, depth: usize, tag: &Tag) {
    indent(out, depth);
    out.push_str("</");
    push_tag(out, tag);
    out.push_str(">\n");
}

/// Writes the start tag of `xmi:XMI` on its own line: its namespace
/// declarations, then the attributes of `outside`, the document's XMI
/// metadata and preserved content, after the bindings they need (ADR 0035
/// D3, ADR 0042).
fn push_wrapper_start(out: &mut String, outside: &Placing<'_>) {
    out.push('<');
    push_wrapper_name(out);
    push_document_attributes(out);
    push_kept_attributes(out, outside.metadata, outside.preserved);
    out.push_str(">\n");
}

/// Writes `xmi:XMI`.
fn push_wrapper_name(out: &mut String) {
    out.push_str(XMI_PREFIX);
    out.push_str(":XMI");
}

/// Writes the namespace declarations of the document element, each after a
/// space. No `xmi:version` is written: the XMI namespace identifies the
/// version (XMI 2.5.1 §7.5.3; ADR 0017 amendment 3).
fn push_document_attributes(out: &mut String) {
    for (prefix, uri) in [(SACM_PREFIX, SACM_NS), (XMI_PREFIX, XMI_NS)] {
        out.push_str(" xmlns:");
        out.push_str(prefix);
        out.push_str("=\"");
        out.push_str(uri);
        out.push('"');
    }
}

/// Writes ` xmi:<local>="`, up to the value.
fn push_attribute_name(out: &mut String, local: &str) {
    out.push(' ');
    out.push_str(XMI_PREFIX);
    out.push(':');
    out.push_str(local);
    out.push_str("=\"");
}

/// Writes two spaces per `depth`.
fn indent(out: &mut String, depth: usize) {
    for _ in 0..depth {
        out.push_str("  ");
    }
}

/// Writes `value` as the content of a double-quoted attribute value: `&`,
/// `<`, `>`, `"`, TAB, LF and CR escaped, and everything else as it is.
fn escape_into(out: &mut String, value: &str) {
    for c in value.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\t' => out.push_str("&#9;"),
            '\n' => out.push_str("&#10;"),
            '\r' => out.push_str("&#13;"),
            other => out.push(other),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{escape_into, is_xml_char, write};
    use crate::model::{Document, ElementId, ElementKind, LangString, MultiLangString};
    use crate::xmi::{Mode, WriteAttribute, WriteError};

    /// The attribute and character a tolerant write of `document` refuses.
    fn refusal(document: &Document) -> Option<(WriteAttribute, char)> {
        match write(document, Mode::Tolerant) {
            Err(WriteError::UnrepresentableCharacter {
                attribute,
                character,
                ..
            }) => Some((attribute, character)),
            _ => None,
        }
    }

    /// A root `id` named `name` with the gid `gid`.
    fn root(id: &str, name: &str, gid: &str) -> Document {
        let mut document = Document::new();
        let id = ElementId::new(id);
        let named = Some(LangString::new(name));
        let inserted = document.insert_node(None, ElementKind::ArgumentPackage, id.clone(), named);
        assert_eq!(inserted, Ok(()));
        assert_eq!(document.set_gid(&id, Some(gid.to_owned())), Ok(()));
        document
    }

    /// No read input can hold a gid XML cannot represent, so the check is
    /// pinned here: after the id, before the name (ADR 0025).
    #[test]
    fn a_gid_xml_cannot_represent_is_refused_after_the_id_and_before_the_name() {
        assert_eq!(
            refusal(&root("p", "P", "g\u{1}")),
            Some((WriteAttribute::Gid, '\u{1}'))
        );
        assert_eq!(
            refusal(&root("p", "P\u{2}", "g\u{FFFE}")),
            Some((WriteAttribute::Gid, '\u{FFFE}'))
        );
        assert_eq!(
            refusal(&root("p\u{3}", "P", "g\u{1}")),
            Some((WriteAttribute::Id, '\u{3}'))
        );
        let written = write(&root("p", "P", "a\tb"), Mode::Strict);
        assert!(
            written
                .as_deref()
                .is_ok_and(|text| text.contains(" xmi:id=\"p\" gid=\"a&#9;b\">")),
            "{written:?}"
        );
    }

    /// A `TaggedValue`'s content is checked before its key, as it is written.
    #[test]
    fn a_content_value_is_checked_before_a_key_value() {
        let mut document = root("p", "P", "g");
        let bad = |content: &str| MultiLangString::from(LangString::new(content));
        let inserted = document.insert_element(
            Some(&ElementId::new("p")),
            ElementKind::TaggedValue,
            ElementId::new("t"),
            None,
            Some(bad("v\u{4}")),
            Some(bad("k\u{5}")),
        );
        assert_eq!(inserted, Ok(()));
        assert_eq!(
            refusal(&document),
            Some((WriteAttribute::ContentValueContent, '\u{4}'))
        );
    }

    /// An end held both by elements and, as preserved content, by an empty
    /// attribute of its name is written in the element form, so the start
    /// tag carries the attribute once, and it reads back the same (ADR 0033).
    #[test]
    fn an_end_beside_a_preserved_attribute_of_its_name_is_written_as_elements() {
        use crate::xmi::{ReadOptions, read};
        let input = concat!(
            "<sacm:ArgumentPackage xmlns:sacm=\"http://www.omg.org/spec/SACM/20220301\" ",
            "xmlns:xmi=\"http://www.omg.org/spec/XMI/20131001\" xmi:id=\"p\"><name content=\"P\"/>",
            "<argumentElement xmi:type=\"sacm:Claim\" xmi:id=\"c1\" metaClaim=\"\">",
            "<name content=\"C1\"/><metaClaim xmi:idref=\"c2\"/><metaClaim xmi:idref=\"p\"/>",
            "</argumentElement><argumentElement xmi:type=\"sacm:Claim\" xmi:id=\"c2\"/>",
            "</sacm:ArgumentPackage>"
        );
        let read_back = |text: &str| match read(text.as_bytes(), &ReadOptions::default()) {
            Ok(output) => output.into_document(),
            Err(error) => panic!("{error}: {text}"),
        };
        let document = read_back(input);
        let Ok(out) = write(&document, Mode::Tolerant) else {
            panic!("the tolerant write refused the document");
        };
        assert_eq!(out.matches("metaClaim=").count(), 1, "{out}");
        assert!(
            out.contains(
                "<argumentElement xmi:type=\"sacm:Claim\" xmi:id=\"c1\" metaClaim=\"\">\n"
            ) && out.contains(
                "    <metaClaim xmi:idref=\"c2\" />\n    <metaClaim xmi:idref=\"p\" />\n"
            ),
            "{out}"
        );
        let back = read_back(&out);
        assert!(back == document, "{out}");
        assert_eq!(write(&back, Mode::Tolerant).ok(), Some(out));
    }

    #[test]
    fn xml_char_bounds() {
        for c in [
            '\t',
            '\n',
            '\r',
            ' ',
            '\u{D7FF}',
            '\u{E000}',
            '\u{FFFD}',
            '\u{10000}',
            '\u{10FFFF}',
        ] {
            assert!(is_xml_char(c), "U+{:04X}", u32::from(c));
        }
        for c in [
            '\0', '\u{8}', '\u{B}', '\u{C}', '\u{1F}', '\u{FFFE}', '\u{FFFF}',
        ] {
            assert!(!is_xml_char(c), "U+{:04X}", u32::from(c));
        }
    }

    #[test]
    fn escaping_covers_the_pinned_characters_only() {
        let mut out = String::new();
        escape_into(&mut out, "&<>\"'\t\n\r\u{e9}");
        assert_eq!(out, "&amp;&lt;&gt;&quot;'&#9;&#10;&#13;\u{e9}");
    }
}
